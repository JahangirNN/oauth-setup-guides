import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { getGuide } from "@/lib/store";
import { CoveragePill, StatusBadge } from "@/components/Badges";
import { CopyLinkButton } from "@/components/CopyLinkButton";
import { EvidenceAppendix } from "@/components/EvidenceAppendix";
import { GuideHeaderCards } from "@/components/GuideHeaderCards";
import { GuideMarkdown } from "@/components/GuideMarkdown";
import { SourcesList } from "@/components/SourcesList";
import { formatDate, formatDuration, plural } from "@/components/labels";

export const dynamic = "force-dynamic";

type GuidePageProps = {
  params: Promise<{ slug: string }>;
};

export async function generateMetadata({ params }: GuidePageProps): Promise<Metadata> {
  const { slug } = await params;
  const guide = await getGuide(slug);

  if (!guide) return { title: "Guide not found" };

  return {
    title: `${guide.header.appName} OAuth setup`,
    description: guide.header.tagline,
  };
}

export default async function GuidePage({ params }: GuidePageProps) {
  const { slug } = await params;
  const guide = await getGuide(slug);

  if (!guide) notFound();

  const { header, evidenceSummary } = guide;

  return (
    <main className="mx-auto max-w-[1100px] px-6 pb-24 pt-10">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <Link href="/" className="text-sm text-muted transition-colors hover:text-ink">
          ← All guides
        </Link>
        <div className="flex flex-wrap gap-2">
          <CopyLinkButton />
          <a
            href={`/api/guide/${guide.slug}/markdown`}
            download
            className="btn btn-secondary"
          >
            <svg
              viewBox="0 0 24 24"
              className="h-3.5 w-3.5"
              fill="none"
              stroke="currentColor"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
              aria-hidden="true"
            >
              <path d="M12 3v12" />
              <path d="m7 10 5 5 5-5" />
              <path d="M5 21h14" />
            </svg>
            Download .md
          </a>
        </div>
      </div>

      <header className="mt-8 max-w-3xl">
        <div className="flex flex-wrap items-center gap-3">
          <span className="font-mono text-xs text-muted">{header.domain}</span>
          <CoveragePill coverage={header.coverage} />
        </div>
        <h1 className="mt-2 text-4xl font-semibold tracking-tight text-ink sm:text-5xl">
          {header.appName}
        </h1>
        <p className="mt-3 text-lg leading-relaxed text-muted">{header.tagline}</p>
        <p className="mt-3 flex flex-wrap items-center gap-x-2 gap-y-1 text-sm text-muted">
          <span>
            Last verified{" "}
            <time dateTime={header.lastVerified} className="text-ink-soft">
              {formatDate(header.lastVerified)}
            </time>
          </span>
          <span aria-hidden="true">·</span>
          <span>
            {guide.sources.length} {plural(guide.sources.length, "source")}
          </span>
          <span aria-hidden="true">·</span>
          <span>
            {guide.claims.length} {plural(guide.claims.length, "claim")}
          </span>
        </p>
      </header>

      <GuideHeaderCards header={header} />

      <div className="mx-auto mt-14 max-w-[760px]">
        <article aria-label={`${header.appName} setup guide`}>
          <GuideMarkdown markdown={guide.markdown} />
        </article>

        <div className="mt-14 space-y-12">
          <EvidenceAppendix claims={guide.claims} inferences={guide.inferences ?? []} />
          <SourcesList sources={guide.sources} />

          <footer className="border-t border-line pt-6 text-sm leading-relaxed text-muted">
            <p>
              Generated by <span className="font-medium text-ink">{guide.model}</span> in{" "}
              {formatDuration(guide.durationMs)}.{" "}
              <span className="font-medium text-ink">{evidenceSummary.quotesVerified}</span> quotes
              verified, {evidenceSummary.quotesRejected} rejected.
            </p>
            <div className="mt-3 rounded-lg border border-line bg-subtle/60 p-4 text-xs leading-relaxed">
              <p>
                <span className="font-medium text-ink">Documented ≠ tested.</span> Items marked{" "}
                <StatusBadge status="documented" /> are sourced from official docs, not executed.
              </p>
              {evidenceSummary.byStatus.tested === 0 ? (
                <p className="mt-1.5">No flow was executed for this guide.</p>
              ) : null}
            </div>

            {(evidenceSummary.unsourcedLinks?.length ?? 0) > 0 ||
            (evidenceSummary.numericViolations?.length ?? 0) > 0 ? (
              <div className="mt-3 rounded-lg border border-amber-200 bg-amber-50 p-4 text-xs leading-relaxed text-amber-950">
                <p className="font-medium">Grounding check</p>
                {(evidenceSummary.unsourcedLinks?.length ?? 0) > 0 ? (
                  <div className="mt-1">
                    <p>
                      {evidenceSummary.unsourcedLinks!.length}{" "}
                      {plural(evidenceSummary.unsourcedLinks!.length, "URL")} in the draft{" "}
                      {evidenceSummary.unsourcedLinks!.length === 1 ? "does" : "do"} not appear in a
                      cited source. The link may still be correct, but it is not evidence-backed.
                    </p>
                    <ul className="mt-1 space-y-0.5 font-mono text-[11px]">
                      {evidenceSummary.unsourcedLinks!.map((url) => (
                        <li key={url} className="break-all">
                          {url}
                        </li>
                      ))}
                    </ul>
                  </div>
                ) : null}
                {(evidenceSummary.numericViolations?.length ?? 0) > 0 ? (
                  <p className="mt-1">
                    Unmatched durations or counts:{" "}
                    <span className="font-mono">
                      {evidenceSummary.numericViolations!.join(", ")}
                    </span>
                    .
                  </p>
                ) : null}
              </div>
            ) : (
              <div className="mt-3 rounded-lg border border-line bg-subtle/60 p-4 text-xs leading-relaxed">
                <p>
                  <span className="font-medium text-ink">Grounding check passed.</span> Every URL and
                  numeric claim in the draft traces back to a cited source.
                </p>
              </div>
            )}
          </footer>
        </div>
      </div>
    </main>
  );
}
